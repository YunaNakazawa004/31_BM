//************************************************************************
// 静的メンバ変数宣言
//************************************************************************
int CField::m_nIdxTexture = -1;			// テクスチャのインデックス

//========================================================================
// テクスチャの生成
//========================================================================
HRESULT CField::Load(const char* pFilename)
{
	// ローカル変数宣言
	CTexture* pTexture = CManager::GetTexture();			// テクスチャへのポインタ

	// テクスチャの設定
	m_nIdxTexture = pTexture->Register(pFilename);

	if (m_nIdxTexture == -1)
	{// テクスチャが設定できていない
		OutputDebugStringA("! ! ! テクスチャの設定に失敗しました ! ! !\n");

		return E_FAIL;
	}

	return S_OK;
}

//========================================================================
// テクスチャの破棄
//========================================================================
void CField::Unload(void)
{
	// テクスチャのインデックスを削除
	memset(&m_nIdxTexture, -1, sizeof m_nIdxTexture);
}

//========================================================================
// 地面クラスの生成処理
//========================================================================
CField* CField::Create(const D3DXVECTOR3 pos, const float fWidth, const float fDepth)
{
#ifndef LIST
	if (CObject::GetNumAll() >= MAX_OBJECT)
	{// 最大数のオブジェクトが存在する
		OutputDebugStringA("! ! ! オブジェクトの最大数に達しています ! ! !\n");

		return nullptr;
	}
#endif

	CField* pField = nullptr;

	if (pField == nullptr)
	{// NULLチェック
		// 地面の生成
		pField = new CField;
	}

	if (pField != nullptr)
	{// NULLチェック
		// 初期化処理
		if (FAILED(pField->Init(pos, fWidth,  fDepth)))
		{// もし失敗した場合
			OutputDebugStringA("! ! ! 地面の初期化に失敗しました ! ! !\n");

			return nullptr;
		}

		// テクスチャを設定
		pField->BindTexture(m_nIdxTexture);

		// 種類を設定
		pField->SetType(TYPE_FIELD);

		return pField;
	}

	OutputDebugStringA("! ! ! 地面の生成に失敗しました ! ! !\n");

	return nullptr;
}

